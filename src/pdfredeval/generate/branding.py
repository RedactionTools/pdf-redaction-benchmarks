"""The provenance banner across the head of every generated page.

A case travels: uploaded to a stranger's web form, downloaded again, printed,
screenshotted, pasted into a ticket. By the time someone disputes a result the page may be
all that is left, so it states who made it, with what, and when — at the top, where a
reader looks first and where a crop is least likely to lose it.

Deliberately absent: the **seed**. This page is handed to the vendor being measured, and
the seed is the key to regenerating a holdout case.

The mark is the Redaction Tools logo, vendored from the site's own asset so the page and
the site cannot drift apart. It is decoded with `pngread` rather than Pillow: generation
is meant to work from a bare `uv sync`, and the brand mark should not be conditional on
an optional extra.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone
from functools import lru_cache
from pathlib import Path
from typing import TYPE_CHECKING

from .pngread import flatten, read_rgba
from .raster import Raster

if TYPE_CHECKING:  # pragma: no cover
    from .builder import CaseBuilder
    from .layout import Slot

PROJECT_URL = "https://redaction-tools.com"
#: This tool's own repository - not the site's. A page in dispute should lead to the
#: generator that produced it.
REPO_URL = "https://github.com/RedactionTools/pdf-redaction-benchmarks"
WORDMARK = "Pdf Redaction Benchmarks"
BYLINE = "by Redaction Tools"
TAGLINE = "Open-source catalog and benchmark of redaction tools"
#: Set plain rather than tracked-out: at 51 characters the phrase is a sentence, and
#: letter-spacing it would both overrun the URLs and read worse.
TAGLINE_SIZE = 5.6
WORDMARK_SIZE = 10.5
BYLINE_SIZE = 6.2
URL_SIZE = 5.3

# Grey ramp. Monochrome on purpose: a coloured banner could interact with the polarity
# and contrast conditions being measured further down the page.
INK = 0.10
MUTED = 0.46
RULE = 0.30
BAND = 0.955
TILE = 0.12

#: Internal padding for the banner panel. Content flush against a tinted panel's edge
#: reads as a mistake; the inset is what makes it read as a panel.
PAD_X = 11.0
PAD_Y = 5.0
CAPTION_H = 11.0


def resolve_generated_at(value: str | datetime | None = None) -> str:
    """UTC ISO-8601, to the second.

    Precedence: an explicit value, then `SOURCE_DATE_EPOCH`, then the clock. The first two
    make generation reproducible; the ground truth records whichever was used, so a case
    can always be regenerated byte-for-byte with `--generated-at`.
    """
    if isinstance(value, datetime):
        return value.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if value:
        return value
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    if epoch:
        return datetime.fromtimestamp(int(epoch), tz=timezone.utc).strftime(
            "%Y-%m-%dT%H:%M:%SZ"
        )
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def pdf_date(iso: str) -> str:
    """ISO-8601 to a PDF date string, `D:YYYYMMDDHHmmSSZ`."""
    stamp = datetime.strptime(iso, "%Y-%m-%dT%H:%M:%SZ")
    return f"D:{stamp.strftime('%Y%m%d%H%M%S')}Z"


def caption(case_id: str, version: str, generated_at: str) -> str:
    """The provenance line: what made this page, from what, when.

    The package name and version live here rather than in the wordmark. The banner above
    says whose benchmark this is; this line says exactly which build produced the bytes,
    which is what someone reproducing a disputed result needs.
    """
    return (
        f"case {case_id}   ·   generated {generated_at}"
        f"   ·   pdfredeval {version}"
    )


def brand_strings(case_id: str, version: str, generated_at: str) -> tuple[str, ...]:
    """Every string the banner puts on the page.

    Probe values must not collide with any of them: the scorer hunts each disclosure unit
    across the whole output, banner included.
    """
    return (
        WORDMARK,
        BYLINE,
        TAGLINE,
        f"{WORDMARK} {BYLINE}",
        PROJECT_URL,
        REPO_URL,
        PROJECT_URL.removeprefix("https://"),
        REPO_URL.removeprefix("https://"),
        caption(case_id, version, generated_at),
        case_id,
    )


LOGO_PATH = Path(__file__).parent / "assets" / "mark-96.png"


@lru_cache(maxsize=4)
def _logo_rgb(background: float) -> tuple[int, int, bytes]:
    """Decode the mark once and composite it onto the banner's grey.

    Flattened rather than carried as RGBA with an SMask: the banner has no transparency
    to preserve, and a soft mask is one more object in a file whose structure is itself
    under test.
    """
    width, height, rgba = read_rgba(LOGO_PATH)
    return width, height, bytes(flatten(width, height, rgba, background))


def logo_raster(background: float = BAND) -> Raster:
    width, height, rgb = _logo_rgb(background)
    return Raster(width, height, channels=3, samples=bytearray(rgb))


def draw_mark(builder: CaseBuilder, x: float, y: float, size: float) -> None:
    """The Redaction Tools shield: a document struck through by a redaction bar."""
    builder.image(logo_raster(BAND), x, y, size, size)


def draw_banner(
    builder: CaseBuilder, slot: Slot, *, case_id: str, version: str, generated_at: str
) -> None:
    """Fill the reserved strip at the head of the page."""
    from .pdf import COURIER, COURIER_BOLD

    band_y = slot.y + CAPTION_H
    band_h = slot.height - CAPTION_H
    builder.rect(slot.x, band_y, slot.width, band_h, gray=BAND)

    mark = band_h - 2 * PAD_Y
    mark_x = slot.x + PAD_X
    draw_mark(builder, mark_x, band_y + PAD_Y, mark)

    text_x = mark_x + mark + 9.0
    builder.text(WORDMARK, text_x, band_y + band_h * 0.55, font=COURIER_BOLD,
                 size=WORDMARK_SIZE, gray=INK)
    builder.text(BYLINE, text_x + COURIER_BOLD.width(WORDMARK, WORDMARK_SIZE) + 6.0,
                 band_y + band_h * 0.55, font=COURIER, size=BYLINE_SIZE, gray=MUTED)
    builder.text(TAGLINE, text_x, band_y + band_h * 0.21, font=COURIER,
                 size=TAGLINE_SIZE, gray=MUTED)

    # Full scheme on the URLs: the page gets printed and retyped, and a bare host is an
    # invitation to guess.
    right = slot.x + slot.width - PAD_X
    for i, url in enumerate((PROJECT_URL, REPO_URL)):
        size = URL_SIZE
        builder.text(url, right - COURIER.width(url, size),
                     band_y + band_h * (0.58 - 0.30 * i), font=COURIER, size=size,
                     gray=INK if i == 0 else MUTED)

    builder.rect(slot.x, band_y - 1.4, slot.width, 0.9, gray=RULE)
    builder.text(caption(case_id, version, generated_at), slot.x, slot.y + 2.5,
                 font=COURIER, size=5.2, gray=MUTED)


def banner_columns(slot: Slot) -> tuple[float, float]:
    """(where the left block ends, where the right block starts).

    Exposed so a test can assert the two never meet: the banner is built from measured
    text, and a longer URL or tagline would otherwise overlap silently.
    """
    from .pdf import COURIER, COURIER_BOLD

    band_h = slot.height - CAPTION_H
    mark = band_h - 2 * PAD_Y
    text_x = slot.x + PAD_X + mark + 9.0
    # Whichever of the two left-hand lines is longer decides where the block ends.
    wordmark_line = (COURIER_BOLD.width(WORDMARK, WORDMARK_SIZE) + 6.0
                     + COURIER.width(BYLINE, BYLINE_SIZE))
    left_end = text_x + max(wordmark_line, COURIER.width(TAGLINE, TAGLINE_SIZE))
    widest = max(COURIER.width(PROJECT_URL, URL_SIZE), COURIER.width(REPO_URL, URL_SIZE))
    return left_end, slot.x + slot.width - PAD_X - widest
