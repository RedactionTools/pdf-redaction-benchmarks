"""Where benchmark data lives on disk: one committed tree per package version.

    benchmarks/
      LATEST                                   the newest version folder, by name
      v0.1.1/
        README.md                              index, regenerated by every command
        cases/<family>/<case_id>/{<case_id>.pdf, ground_truth.json}
        runs/<tool-slug>/<run_id>/{manifest.json, <the delivered PDF>, score/, ...}
        reports/<tool-slug>/                   one tool, every family
        reports/<tool-slug>/<family>/          one tool, one family
        reports/_summary/[<family>/]           every tool

A version folder is keyed by the package version because that is what stamps the
generated pages: a case made by 0.1.1 and one made by 0.2.0 are different cases even
from the same seed, and a score is only comparable against the cases it was run on.

File names carry their own identity - `pii-detection-1.pdf`, not `case.pdf` - because
a PDF gets uploaded to a vendor, attached to a ticket and downloaded again, and outside
its folder `case.pdf` says nothing. A run's output keeps whatever name the tool gave it:
the run folder already says which tool, and renaming every download is busywork that
invites re-saving it. `collect` records the name in the manifest.

Stdlib only, and nothing from `types` or `tools`: both import the naming helpers here.
"""

from __future__ import annotations

import os
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from enum import Enum
from pathlib import Path

from ._version import __version__
from .errors import BenchmarkError

ENV_HOME = "PDFREDEVAL_HOME"
DEFAULT_ROOT = Path("benchmarks")
LATEST_NAME = "LATEST"
INDEX_NAME = "README.md"
SUMMARY_DIR = "_summary"

#: Names a pre-versioned tree used; still read, never written.
LEGACY_CASE_PDF = "case.pdf"
LEGACY_OUTPUT_PDF = "output.pdf"


# --- names ------------------------------------------------------------------------


def version_tag(version: str = __version__) -> str:
    return version if version.startswith("v") else f"v{version}"


def tool_slug(tool_id: str) -> str:
    """`acme:web` -> `acme-web`: the form a tool takes in paths and run ids."""
    return tool_id.replace(":", "-")


def case_pdf_name(case_id: str) -> str:
    return f"{case_id}.pdf"


def output_pdf_name(case_id: str) -> str:
    """The name suggested for a run's output. Any name is accepted."""
    return f"{case_id}.pdf"


def case_pdf_path(case_dir: Path, case_id: str, named: str | None = None) -> Path:
    """The case's PDF: the name ground truth records, then `<case_id>.pdf`, then legacy."""
    for name in (named, case_pdf_name(case_id)):
        if name and (case_dir / name).exists():
            return case_dir / name
    legacy = case_dir / LEGACY_CASE_PDF
    return legacy if legacy.exists() else case_dir / case_pdf_name(case_id)


def output_pdf_path(
    run_dir: Path, case_id: str, tool_id: str, named: str | None = None
) -> Path:
    """A run's delivered PDF, whatever it is called.

    The name the manifest recorded wins; then the names this framework has suggested
    (`<case_id>.pdf`, the earlier `<case_id>__<tool>.pdf`, `output.pdf`); then the only
    PDF in the folder. Two unexplained PDFs are an error, not a guess: scoring the wrong
    one would publish a number about a file nobody meant to submit. With none, the
    suggested path - where the output is expected to arrive.
    """
    suggested = (output_pdf_name(case_id),
                 f"{case_id}__{tool_slug(tool_id)}.pdf", LEGACY_OUTPUT_PDF)
    for name in (named, *suggested):
        if name and (run_dir / name).is_file():
            return run_dir / name
    found = sorted(p for p in run_dir.glob("*.pdf") if p.is_file()) \
        if run_dir.is_dir() else []
    if len(found) == 1:
        return found[0]
    if found:
        raise BenchmarkError(
            f"{len(found)} PDFs in {run_dir}: {', '.join(p.name for p in found)}. "
            f"Keep only the tool's output there, or name it {output_pdf_name(case_id)}"
        )
    return run_dir / output_pdf_name(case_id)


def family_of(case_id: str) -> str | None:
    """The family a case id was generated under: `pii-detection-1` -> `pii-detection`.

    Longest prefix wins, so a family whose name extends another's still resolves.
    """
    from .generate import FAMILIES

    for family in sorted(FAMILIES, key=len, reverse=True):
        if case_id.startswith(f"{family}-"):
            return family
    return None


def resolve_case(case_id: str, cases_root: Path | str) -> Path:
    """`cases_root/<family>/<case_id>`, falling back to a flat `cases_root/<case_id>`."""
    root = Path(cases_root)
    family = family_of(case_id)
    nested = root / family / case_id if family else None
    if nested is not None and (nested / "ground_truth.json").exists():
        return nested
    flat = root / case_id
    if (flat / "ground_truth.json").exists() or nested is None:
        return flat
    return nested


# --- the tree ---------------------------------------------------------------------


def bench_root() -> Path:
    return Path(os.environ.get(ENV_HOME) or DEFAULT_ROOT)


@dataclass(frozen=True, slots=True)
class Workspace:
    root: Path
    version: str

    @classmethod
    def from_args(cls, root: Path | str | None, version: str | None) -> Workspace:
        return cls(Path(root) if root else bench_root(), version_tag(version or __version__))

    @property
    def home(self) -> Path:
        return self.root / self.version

    @property
    def cases_root(self) -> Path:
        return self.home / "cases"

    @property
    def runs_root(self) -> Path:
        return self.home / "runs"

    @property
    def reports_root(self) -> Path:
        return self.home / "reports"

    def cases_dir(self, family: str) -> Path:
        return self.cases_root / family

    def runs_dir(self, tool_id: str) -> Path:
        return self.runs_root / tool_slug(tool_id)

    def reports_dir(self, tool_id: str | None = None, family: str | None = None) -> Path:
        base = self.reports_root / (tool_slug(tool_id) if tool_id else SUMMARY_DIR)
        return base / family if family else base

    def contains(self, path: Path | str) -> bool:
        try:
            Path(path).resolve().relative_to(self.home.resolve())
        except ValueError:
            return False
        return True

    # --- index ---

    def write_index(self) -> Path | None:
        """Regenerate `README.md` for this version, and `LATEST` beside it."""
        if not self.home.is_dir():
            return None
        lines = [
            f"# Benchmark {self.version}",
            "",
            "Generated by `pdfredeval`; rewritten on every command, so edits here are lost.",
            "",
        ]

        families = sorted(p for p in self.cases_root.iterdir() if p.is_dir()) \
            if self.cases_root.is_dir() else []
        if families:
            lines += ["## Cases", "", "| family | cases |", "|---|---:|"]
            for fam in families:
                count = sum(1 for c in fam.iterdir() if (c / "ground_truth.json").exists())
                lines.append(f"| [{fam.name}](cases/{fam.name}/) | {count} |")
            lines.append("")

        tools = sorted(p for p in self.runs_root.iterdir() if p.is_dir()) \
            if self.runs_root.is_dir() else []
        if tools:
            lines += ["## Runs", "", "| tool | runs | scored |", "|---|---:|---:|"]
            for tool in tools:
                runs = [r for r in tool.iterdir() if (r / "handle.json").exists()
                        or (r / "manifest.json").exists()]
                scored = sum(1 for r in runs if (r / "score" / "report.json").exists())
                lines.append(f"| [{tool.name}](runs/{tool.name}/) | {len(runs)} | {scored} |")
            lines.append("")

        reports = sorted(self.reports_root.rglob("report.md")) \
            if self.reports_root.is_dir() else []
        if reports:
            lines += ["## Reports", ""]
            for md in reports:
                rel = md.relative_to(self.home)
                label = str(md.parent.relative_to(self.reports_root))
                html = md.with_suffix(".html")
                extra = f" ([html]({html.relative_to(self.home)}))" if html.exists() else ""
                lines.append(f"- [{label}]({rel}){extra}")
            lines.append("")

        index = self.home / INDEX_NAME
        index.write_text("\n".join(lines))
        (self.root / LATEST_NAME).write_text(_latest(self.root) + "\n")
        return index


def _latest(root: Path) -> str:
    def key(name: str) -> tuple:
        return tuple(int(n) if n.isdigit() else -1 for n in re.split(r"[.+-]", name[1:]))

    versions = [p.name for p in root.iterdir() if p.is_dir() and p.name.startswith("v")]
    return max(versions, key=key)


# --- overwriting ------------------------------------------------------------------


class Overwrite(Enum):
    ASK = "ask"
    FORCE = "force"
    SKIP = "skip"

    @classmethod
    def from_flags(cls, *, force: bool, skip: bool) -> Overwrite:
        return cls.FORCE if force else cls.SKIP if skip else cls.ASK


def _interactive() -> bool:
    return sys.stdin.isatty() and sys.stderr.isatty()


def confirm_overwrite(existing: Sequence[Path], what: str, policy: Overwrite) -> bool:
    """True to replace `existing`, False to leave it be. Raises to abort.

    Asks only a person at a terminal. Anything else - CI, a pipe, a test - has to say
    what it wants with --force or --skip-existing, because a guess here either destroys
    committed data or silently does nothing.
    """
    if not existing or policy is Overwrite.FORCE:
        return True
    if policy is Overwrite.SKIP:
        return False
    listing = "\n".join(f"  {p}" for p in existing[:10])
    more = f"\n  ... and {len(existing) - 10} more" if len(existing) > 10 else ""
    if not _interactive():
        raise BenchmarkError(
            f"{len(existing)} {what} already exist:\n{listing}{more}\n"
            f"pass --force to overwrite them or --skip-existing to keep them"
        )
    print(f"{len(existing)} {what} already exist:\n{listing}{more}", file=sys.stderr)
    while True:
        print("[o]verwrite / [s]kip existing / [a]bort? ", end="", file=sys.stderr,
              flush=True)
        answer = sys.stdin.readline().strip().lower()
        if answer in ("o", "overwrite"):
            return True
        if answer in ("s", "skip"):
            return False
        if answer in ("a", "abort", ""):
            raise BenchmarkError("aborted; nothing was overwritten")
